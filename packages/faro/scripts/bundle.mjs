// Builds src/static.ts into one minified script for the static sites, which
// have no bundler: apps/site/assets/faro.js and apps/docs/static/js/faro.js.
// Rerun after changing @poweur/faro or upgrading the Faro SDK.
import { build } from "esbuild";
import { copyFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..", "..");
const site = join(root, "apps/site/assets/faro.js");
const docs = join(root, "apps/docs/static/js/faro.js");

await build({
  entryPoints: [join(here, "..", "src", "static.ts")],
  bundle: true,
  minify: true,
  format: "iife",
  target: "es2019",
  legalComments: "eof",
  outfile: site,
  banner: { js: "/* Poweur telemetry: Grafana Faro, anonymous, first-party. Generated by packages/faro (pnpm --filter @poweur/faro bundle). */" },
});
copyFileSync(site, docs);
console.log(`wrote ${site}\nwrote ${docs}`);
